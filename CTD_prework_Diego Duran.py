#Script checks player health and level for possible low level-health bonus and if both conditions are met a bonus-shield is applied
#Inputs ask for the players current health and level

players_health = input("Enter current health: ")
players_level = input("Enter current level: ")

#Checks players health if they get low-health bonus
if int(players_level) < 10:
  players_health = int(players_health) + 20
  print("Low level-health bonus applied")
else: print("No low level-health bonus applied")

#Checks players health and level for possible bonus-shield
if int(players_level) < 10 and int(players_health) < 50:
  print("bonus-shield applied")
else: print("No bonus-shield applied")

#Prints evaluated health-bonus and players level
print("Current health:" + str(players_health) + " " + "Players level:" + str(players_level))

